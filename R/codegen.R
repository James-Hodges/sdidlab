#' Write a runnable R script for a set of specifications
#'
#' Generates a self-contained script that loads the data, reads the
#' specifications, fits them with [run_specs()] and prints the results
#' table. By default the specifications are embedded in the script as YAML,
#' so the one file reproduces the results; pass `spec_file` to refer to a
#' separate YAML file instead (see [write_specs_yaml()]).
#'
#' Each specification is fitted with its own seed ([seed_for()]), so the
#' script reproduces every standard error regardless of order.
#'
#' @param specs A list of [sdid_spec()]s (or a single one).
#' @param path File to write, or `NULL` to return the script as text.
#' @param data_code R code, as a string, that creates an [sdid_panel()]
#'   called `panel`. For example
#'   `'panel <- sdid_panel(read.csv("my_data.csv"), unit = "state", time = "year", outcome = "y")'`.
#' @param title A title for the script's header comment.
#' @param spec_file Path the script should read the specifications from,
#'   instead of embedding them.
#'
#' @return The path, invisibly, or the script text when `path = NULL`.
#'
#' @examples
#' code <- write_spec_script(
#'   list(sdid_spec(label = "Prop 99", inference = list(replications = 50))),
#'   path = NULL,
#'   data_code = "panel <- prop99_panel()",
#'   title = "Proposition 99"
#' )
#' cat(code)
#'
#' @export
write_spec_script <- function(specs, path, data_code, title = "sdidlab analysis",
                              spec_file = NULL) {
  if (inherits(specs, "sdid_spec")) specs <- list(specs)
  if (!length(specs)) cli::cli_abort("No specifications to write.")
  if (!is.character(data_code) || length(data_code) != 1L) {
    cli::cli_abort("{.arg data_code} must be a single string of R code creating {.code panel}.")
  }
  yaml_text <- write_specs_yaml(specs, NULL, title = title)
  if (grepl(")---\"", yaml_text, fixed = TRUE)) {
    cli::cli_abort("The specifications contain text that cannot be embedded; use {.arg spec_file}.")
  }
  spec_block <- if (is.null(spec_file)) {
    c("spec_yaml <- r\"---(",
      sub("\n$", "", yaml_text),
      ")---\"",
      "spec_path <- tempfile(fileext = \".yml\")",
      "writeLines(spec_yaml, spec_path)",
      "specs <- read_specs(spec_path)")
  } else {
    sprintf("specs <- read_specs(%s)", deparse(spec_file))
  }
  lines <- c(
    paste0("# ", title),
    paste0("# Generated by sdidlab ", utils::packageVersion("sdidlab"), " on ", format(Sys.Date()), "."),
    "# Each specification is fitted with its own seed (seed_for()), so every",
    "# standard error reproduces exactly, whatever order the specs are run in.",
    "",
    "library(sdidlab)",
    "",
    "# -- Data ---------------------------------------------------------------",
    data_code,
    "",
    "# -- Specifications -----------------------------------------------------",
    spec_block,
    "",
    "# -- Fit ------------------------------------------------------------------",
    "runs <- run_specs(specs, panel, seed_each = TRUE)",
    "results <- sdid_results_table(runs)",
    "print(results, row.names = FALSE)"
  )
  text <- paste0(paste(lines, collapse = "\n"), "\n")
  tryCatch(parse(text = text), error = function(e) {
    cli::cli_abort(c("The generated script does not parse.", x = conditionMessage(e)))
  })
  if (is.null(path)) return(text)
  writeLines(text, path, useBytes = TRUE)
  invisible(path)
}
